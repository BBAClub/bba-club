import {
  defineField,
  defineType,
} from "sanity";

export const eventRegistrationType =
  defineType({
    name:
      "eventRegistration",

    title:
      "Event Registration",

    type:
      "document",

    fields: [
      /*
        EVENT
      */

      defineField({
        name: "event",

        title: "Event",

        type: "reference",

        to: [
          {
            type: "event",
          },
        ],

        validation: (Rule) =>
          Rule.required(),
      }),

      /*
        REGISTRATION STATUS
      */

      defineField({
        name: "status",

        title: "Status",

        type: "string",

        options: {
          list: [
            {
              title:
                "Pending payment",

              value:
                "pending-payment",
            },

            {
              title:
                "Confirmed",

              value:
                "confirmed",
            },

            {
              title:
                "Waitlist",

              value:
                "waitlist",
            },

            {
              title:
                "Cancelled",

              value:
                "cancelled",
            },

            {
              title:
                "Checked in",

              value:
                "checked-in",
            },
          ],

          layout:
            "dropdown",
        },

        initialValue:
          "confirmed",

        validation: (Rule) =>
          Rule.required(),
      }),

      defineField({
        name:
          "registeredAt",

        title:
          "Registered At",

        type:
          "datetime",

        initialValue: () =>
          new Date()
            .toISOString(),

        validation: (Rule) =>
          Rule.required(),
      }),

      /*
        ATTENDEE
      */

      defineField({
        name:
          "firstName",

        title:
          "First Name",

        type:
          "string",

        validation: (Rule) =>
          Rule.required(),
      }),

      defineField({
        name:
          "lastName",

        title:
          "Last Name",

        type:
          "string",

        validation: (Rule) =>
          Rule.required(),
      }),

      defineField({
        name: "email",

        title: "Email",

        type: "string",

        validation: (Rule) =>
          Rule
            .required()
            .email(),
      }),

      defineField({
        name:
          "university",

        title:
          "University / School",

        type:
          "string",

        description:
          "Optional. For example VŠE.",
      }),

      defineField({
        name: "note",

        title:
          "Registration Note",

        type: "text",

        rows: 3,

        description:
          "Optional note from the attendee.",
      }),

      /*
        TICKET
      */

      defineField({
        name:
          "ticketCode",

        title:
          "Ticket Code",

        type:
          "string",

        readOnly: true,

        description:
          "Unique ticket identifier generated by the website.",
      }),

      /*
        PAYMENT
      */

      defineField({
        name:
          "paymentStatus",

        title:
          "Payment Status",

        type:
          "string",

        options: {
          list: [
            {
              title:
                "Not required",

              value:
                "not_required",
            },

            {
              title:
                "Pay on site",

              value:
                "pay_on_site",
            },

            {
              title:
                "Pending",

              value:
                "pending",
            },

            {
              title:
                "Paid",

              value:
                "paid",
            },

            {
              title:
                "Failed",

              value:
                "failed",
            },

            {
              title:
                "Refunded",

              value:
                "refunded",
            },
          ],

          layout:
            "dropdown",
        },

        readOnly: true,

        description:
          "Payment state managed automatically by the website.",
      }),

      defineField({
        name:
          "paymentProvider",

        title:
          "Payment Provider",

        type:
          "string",

        readOnly: true,

        description:
          "Payment provider used for this registration.",
      }),

      defineField({
        name:
          "paymentTransactionId",

        title:
          "Comgate Transaction ID",

        type:
          "string",

        readOnly: true,

        description:
          "Transaction identifier returned by Comgate.",
      }),

      defineField({
        name:
          "paymentRedirectUrl",

        title:
          "Payment Redirect URL",

        type:
          "url",

        readOnly: true,

        description:
          "Checkout URL returned by Comgate.",
      }),

      defineField({
        name:
          "paymentAmount",

        title:
          "Payment Amount",

        type:
          "number",

        readOnly: true,

        description:
          "Amount charged. Stored as a snapshot of the event price in the payment currency.",
      }),

      defineField({
        name:
          "paymentCurrency",

        title:
          "Payment Currency",

        type:
          "string",

        options: {
          list: [
            {
              title: "CZK",
              value: "CZK",
            },

            {
              title: "EUR",
              value: "EUR",
            },
          ],
        },

        readOnly: true,

        description:
          "Currency used for the payment.",
      }),

      defineField({
        name:
          "paymentCreatedAt",

        title:
          "Payment Created At",

        type:
          "datetime",

        readOnly: true,
      }),

      defineField({
        name:
          "reservationExpiresAt",

        title:
          "Seat Reservation Expires At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Until this time, a pending payment temporarily reserves a seat.",
      }),

      defineField({
        name:
          "paidAt",

        title:
          "Paid At",

        type:
          "datetime",

        readOnly: true,
      }),

      defineField({
        name:
          "refundedAt",

        title:
          "Refunded At",

        type:
          "datetime",

        readOnly: true,
      }),

      defineField({
        name:
          "payOnSiteConfirmedAt",

        title:
          "Pay On Site Confirmed At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when the attendee explicitly confirmed the fallback option to pay at the venue.",
      }),

      /*
        EMAIL DELIVERY
      */

      defineField({
        name:
          "confirmationEmailSentAt",

        title:
          "Confirmation Email Sent At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when the registration email was accepted for sending.",
      }),

      defineField({
        name:
          "confirmationEmailId",

        title:
          "Confirmation Email ID",

        type:
          "string",

        readOnly: true,

        description:
          "Email identifier returned by the email provider.",
      }),

      defineField({
        name:
          "emailDeliveryStatus",

        title:
          "Email Delivery Status",

        type:
          "string",

        options: {
          list: [
            {
              title:
                "Not sent",

              value:
                "not-sent",
            },

            {
              title:
                "Sent",

              value:
                "sent",
            },

            {
              title:
                "Delayed",

              value:
                "delayed",
            },

            {
              title:
                "Delivered",

              value:
                "delivered",
            },

            {
              title:
                "Bounced",

              value:
                "bounced",
            },

            {
              title:
                "Spam complaint",

              value:
                "complained",
            },

            {
              title:
                "Failed",

              value:
                "failed",
            },
          ],

          layout:
            "dropdown",
        },

        readOnly: true,

        description:
          "Latest known delivery state reported by the email provider.",
      }),

      defineField({
        name:
          "emailDeliveredAt",

        title:
          "Email Delivered At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when the email provider confirmed delivery.",
      }),

      defineField({
        name:
          "emailDelayedAt",

        title:
          "Email Delayed At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when the email provider reported a temporary delivery delay.",
      }),

      defineField({
        name:
          "emailBouncedAt",

        title:
          "Email Bounced At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when delivery failed because the receiving mail server rejected the email.",
      }),

      defineField({
        name:
          "emailComplainedAt",

        title:
          "Email Complaint At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when the recipient reported the email as spam.",
      }),

      defineField({
        name:
          "emailFailedAt",

        title:
          "Email Failed At",

        type:
          "datetime",

        readOnly: true,

        description:
          "Time when sending or delivery failed.",
      }),

      /*
        CHECK-IN
      */

      defineField({
        name:
          "checkedInAt",

        title:
          "Checked In At",

        type:
          "datetime",

        readOnly: true,
      }),
    ],

    /*
      SANITY LIST PREVIEW
    */

    preview: {
      select: {
        firstName:
          "firstName",

        lastName:
          "lastName",

        email:
          "email",

        eventTitle:
          "event.title",

        status:
          "status",

        paymentStatus:
          "paymentStatus",

        emailDeliveryStatus:
          "emailDeliveryStatus",

        confirmationEmailSentAt:
          "confirmationEmailSentAt",

        emailBouncedAt:
          "emailBouncedAt",
      },

      prepare({
        firstName,
        lastName,
        email,
        eventTitle,
        status,
        paymentStatus,
        emailDeliveryStatus,
        confirmationEmailSentAt,
        emailBouncedAt,
      }) {
        const statusLabel =
          status ===
          "pending-payment"
            ? "Payment pending"
            : status ===
                "checked-in"
              ? "✓ Checked in"
              : status ===
                  "confirmed"
                ? "Confirmed"
                : status ===
                    "waitlist"
                  ? "Waitlist"
                  : status ===
                      "cancelled"
                    ? "Cancelled"
                    : status;

        const paymentLabel =
          paymentStatus ===
          "paid"
            ? "Paid"
            : paymentStatus ===
                "pay_on_site"
              ? "Pay on site"
              : paymentStatus ===
                  "pending"
                ? "Payment pending"
                : paymentStatus ===
                    "failed"
                  ? "Payment failed"
                  : paymentStatus ===
                      "refunded"
                    ? "Refunded"
                    : paymentStatus ===
                        "not_required"
                      ? "No payment"
                      : undefined;

        const resolvedEmailStatus =
          emailDeliveryStatus ??
          (
            emailBouncedAt
              ? "bounced"
              : confirmationEmailSentAt
                ? "sent"
                : undefined
          );

        const emailLabel =
          resolvedEmailStatus ===
          "delivered"
            ? "Email delivered"
            : resolvedEmailStatus ===
                "delayed"
              ? "Email delayed"
              : resolvedEmailStatus ===
                  "bounced"
                ? "⚠ Email bounced"
                : resolvedEmailStatus ===
                    "complained"
                  ? "⚠ Spam complaint"
                  : resolvedEmailStatus ===
                      "failed"
                    ? "⚠ Email failed"
                    : resolvedEmailStatus ===
                        "sent"
                      ? "Email sent"
                      : resolvedEmailStatus ===
                          "not-sent"
                        ? "Email not sent"
                        : undefined;

        return {
          title:
            `${firstName ?? ""} ${lastName ?? ""}`.trim() ||
            email ||
            "Registration",

          subtitle: [
            eventTitle,
            statusLabel,
            paymentLabel,
            emailLabel,
            email,
          ]
            .filter(Boolean)
            .join(" · "),
        };
      },
    },
  });
